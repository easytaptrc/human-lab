export const $ = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

export function esc(v) {
  return String(v ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

export const DIAS = ["Domingo", "Lunes", "Martes", "Miércoles", "Jueves", "Viernes", "Sábado"];
export const DIAS_CORTOS = ["D", "L", "M", "M", "J", "V", "S"];
export const MESES = ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"];
export const MESES_CORTOS = ["ene", "feb", "mar", "abr", "may", "jun", "jul", "ago", "sep", "oct", "nov", "dic"];

const pad = (n) => String(n).padStart(2, "0");

export function dateStr(d) {
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}
export function todayStr() { return dateStr(new Date()); }
export function parseDate(s) {
  const [y, m, d] = s.split("-").map(Number);
  return new Date(y, m - 1, d);
}
export function addDays(s, n) {
  const d = parseDate(s);
  d.setDate(d.getDate() + n);
  return dateStr(d);
}
export function addMonths(s, n) {
  const d = parseDate(s);
  const day = d.getDate();
  d.setDate(1);
  d.setMonth(d.getMonth() + n);
  const last = new Date(d.getFullYear(), d.getMonth() + 1, 0).getDate();
  d.setDate(Math.min(day, last));
  return dateStr(d);
}
export function daysBetween(a, b) {
  return Math.round((parseDate(b) - parseDate(a)) / 86400000);
}
export function dowOf(s) { return parseDate(s).getDay(); }
export function startAt(date, time) {
  const [h, m] = time.split(":").map(Number);
  const d = parseDate(date);
  d.setHours(h, m, 0, 0);
  return d;
}
export function fmtDate(s, { long = false } = {}) {
  if (!s) return "—";
  const d = parseDate(s);
  return long
    ? `${DIAS[d.getDay()]} ${d.getDate()} de ${MESES[d.getMonth()]} ${d.getFullYear()}`
    : `${d.getDate()} ${MESES_CORTOS[d.getMonth()]} ${d.getFullYear()}`;
}
export function fmtMoney(n) {
  return Number(n || 0).toLocaleString("es-MX", { style: "currency", currency: "MXN", maximumFractionDigits: 0 });
}

export const digits = (s) => String(s || "").replace(/\D/g, "");

export function waLink(phone, text) {
  let p = digits(phone);
  if (p.length === 10) p = "52" + p; // número local de México
  return `https://wa.me/${p}?text=${encodeURIComponent(text)}`;
}

export function fillTemplate(tpl, data) {
  return String(tpl || "").replace(/\{(\w+)\}/g, (_, k) => data[k] ?? "");
}

export async function sha256(text) {
  const buf = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(text));
  return [...new Uint8Array(buf)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

// Llave secreta del panel de socio: ID + últimos 4 dígitos del teléfono.
export function portalKey(memberId, phone) {
  return sha256(`${String(memberId).trim().toUpperCase()}|${digits(phone).slice(-4)}`);
}

export function randomToken(len = 24) {
  const a = new Uint8Array(len);
  crypto.getRandomValues(a);
  return [...a].map((b) => (b % 36).toString(36)).join("");
}

export function toast(msg, type = "ok") {
  let box = document.getElementById("toasts");
  if (!box) {
    box = document.createElement("div");
    box.id = "toasts";
    document.body.appendChild(box);
  }
  const t = document.createElement("div");
  t.className = `toast toast-${type}`;
  t.textContent = msg;
  box.appendChild(t);
  setTimeout(() => t.classList.add("out"), 3200);
  setTimeout(() => t.remove(), 3700);
}

export const store = {
  get(k, def = null) { try { const v = localStorage.getItem(k); return v ? JSON.parse(v) : def; } catch { return def; } },
  set(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch { /* sin almacenamiento */ } },
  del(k) { try { localStorage.removeItem(k); } catch { /* sin almacenamiento */ } },
};

// Comprime una imagen a data URL (JPEG/WebP o PNG si tiene transparencia) para guardarla en Firestore.
export function compressImage(file, { max = 1600, quality = 0.82, keepAlpha = false } = {}) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onerror = reject;
    reader.onload = () => {
      const img = new Image();
      img.onerror = reject;
      img.onload = () => {
        const scale = Math.min(1, max / Math.max(img.width, img.height));
        const c = document.createElement("canvas");
        c.width = Math.round(img.width * scale);
        c.height = Math.round(img.height * scale);
        c.getContext("2d").drawImage(img, 0, 0, c.width, c.height);
        let out = keepAlpha ? c.toDataURL("image/png") : c.toDataURL("image/webp", quality);
        if (!keepAlpha && !out.startsWith("data:image/webp")) out = c.toDataURL("image/jpeg", quality);
        if (keepAlpha && out.length > 700000) out = c.toDataURL("image/webp", quality);
        resolve(out);
      };
      img.src = reader.result;
    };
    reader.readAsDataURL(file);
  });
}

